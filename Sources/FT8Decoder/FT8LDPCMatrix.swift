    public static let checkToVariables: [[Int]] = {
        generatorRows.enumerated().map { rowIndex, packed in
            var variables: [Int] = []
            variables.reserveCapacity(48)
            for bit in 0..<informationBitCount {
                let byte = packed[bit / 8]
                let mask = UInt8(1 << (7 - (bit % 8)))
                if byte & mask != 0 {
                    variables.append(bit)
                }
            }
            variables.append(informationBitCount + rowIndex)
            return variables
        }
    }()

    public static let variableToChecks: [[Int]] = {
        var result = Array(repeating: [Int](), count: codewordBitCount)
        for (check, variables) in checkToVariables.enumerated() {
            for variable in variables {
                result[variable].append(check)
            }
        }
        return result
    }()

    public static func syndrome(of codeword: FT8BitBuffer) -> [UInt8] {
        guard codeword.count == codewordBitCount else {
            return Array(repeating: 1, count: checkCount)
        }
        return checkToVariables.map { variables in
            variables.reduce(UInt8.zero) { partial, variable in
                partial ^ codeword[variable]
            }
        }
    }

    public static func isValid(_ codeword: FT8BitBuffer) -> Bool {
        syndrome(of: codeword).allSatisfy { $0 == 0 }
    }
